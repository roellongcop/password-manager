// Rows of '0'/'1' to the flat Uint8Array the decoder works with.
export function fixtureMatrix(rows) {
  const dimension = rows.length;
  const matrix = new Uint8Array(dimension * dimension);
  rows.forEach((row, y) => {
    for (let x = 0; x < dimension; x++) matrix[y * dimension + x] = row[x] === '1' ? 1 : 0;
  });
  return { matrix, dimension };
}
